import { createReadStream } from "node:fs";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";
import {
  S3Client,
  PutObjectCommand,
  GetObjectCommand,
  DeleteObjectCommand,
} from "@aws-sdk/client-s3";
import { config } from "./config.js";

// Documents live on the server's own disk unless an S3-compatible bucket is configured.
export const useS3 = () => Boolean(config.S3_BUCKET);
const root = path.resolve(config.STORAGE_DIR);

export const s3 = new S3Client({
  region: config.S3_REGION,
  endpoint: config.S3_ENDPOINT || undefined,
  forcePathStyle: !!config.S3_ENDPOINT,
  ...(config.S3_ACCESS_KEY && config.S3_SECRET_KEY
    ? {
        credentials: {
          accessKeyId: config.S3_ACCESS_KEY,
          secretAccessKey: config.S3_SECRET_KEY,
        },
      }
    : {}),
});

// Keys are "<organizationId>/<uuid>.<ext>" generated by the server; refuse anything that could leave the folder.
function localPath(key: string) {
  const full = path.resolve(root, key);
  if (!full.startsWith(root + path.sep)) throw new Error("INVALID_STORAGE_KEY");
  return full;
}

export async function putObject(key: string, body: Buffer, contentType: string) {
  if (useS3()) {
    await s3.send(
      new PutObjectCommand({
        Bucket: config.S3_BUCKET,
        Key: key,
        Body: body,
        ContentType: contentType,
      }),
    );
    return;
  }
  const full = localPath(key);
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, body, { mode: 0o600 });
}

export async function getObjectStream(key: string): Promise<Readable> {
  if (useS3()) {
    try {
      const file = await s3.send(
        new GetObjectCommand({ Bucket: config.S3_BUCKET, Key: key }),
      );
      return file.Body as Readable;
    } catch (e: any) {
      if (e?.name === "NoSuchKey" || e?.$metadata?.httpStatusCode === 404)
        throw new StorageNotFound();
      throw e;
    }
  }
  const full = localPath(key);
  try {
    await stat(full);
  } catch {
    throw new StorageNotFound();
  }
  return createReadStream(full);
}

export async function getObjectBuffer(key: string): Promise<Buffer> {
  if (useS3()) {
    const object = await s3.send(
      new GetObjectCommand({ Bucket: config.S3_BUCKET, Key: key }),
      { abortSignal: AbortSignal.timeout(30000) },
    );
    return Buffer.from(await object.Body!.transformToByteArray());
  }
  return readFile(localPath(key));
}

export async function deleteObject(key: string) {
  if (useS3()) {
    await s3.send(new DeleteObjectCommand({ Bucket: config.S3_BUCKET, Key: key }));
    return;
  }
  await rm(localPath(key), { force: true });
}

export class StorageNotFound extends Error {}
